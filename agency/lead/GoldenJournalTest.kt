package com.geekinasuit.agency.lead

import com.geekinasuit.agency.pod.PodSpec
import com.geekinasuit.agency.shared.journal.EffectReceiver
import com.geekinasuit.agency.shared.journal.JournalEntry
import com.geekinasuit.agency.shared.journal.SqliteStore
import java.io.File
import org.junit.Assert.fail
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder

/**
 * Pins the exact journal the lead writes, entry by entry, across the scripted ticket walk and a
 * kill at every named boundary the walk reaches, under [LeadAuth.DENY_ALL] and under a ceremony
 * auth. Each scenario's journal is normalized and compared with a golden file under
 * `testdata/golden-journals/`, generated from the daemon before the host/workflow split (#261) and
 * left unchanged by each of the split's PRs. So a split PR that changes what is journaled, in what
 * order, with what origin, payload or idempotency key, fails here.
 *
 * Normalization renames only what differs between runs, by order of first appearance: pod ids,
 * session ids, nonces, and the run's directory. A rename (not a blank) keeps a nonce bound to the
 * wrong gate, or a result attached to the wrong pod, visible. Each line keeps the entry's seq, kind,
 * origin, idempotency key and payload. The rest of the envelope (schema version, chain context, key
 * epoch, salt, commitment, hash, previous hash, signature) is left out: the store sets it, and the
 * salt is random.
 *
 * A kill scenario's golden opens with whether its kill fired. Some boundaries sit before any
 * append (in adopt), so a kill there leaves the journal unchanged; without that line, removing such
 * a fault point would go unnoticed. `INDEX.txt` lists every scenario and the normalizer's volatile
 * patterns, so shrinking the scenario set or widening what is normalized away shows in a diff too.
 *
 * On a mismatch, or a missing golden, the actual journal is written to the test's undeclared
 * outputs, so a golden can be regenerated by reviewing and copying it.
 */
class GoldenJournalTest {

  @get:Rule val tmp = TemporaryFolder()

  /** Thrown by [killAt] to simulate a death at a named boundary: the daemon is discarded, and a
   * fresh one adopts from the journal, as a restarted process would. */
  private class Killed(boundary: String) : RuntimeException("killed at $boundary")

  private enum class Auth(val label: String) {
    DENY_ALL("deny-all"),
    CEREMONY("ceremony"),
  }

  private val happy = Auth.values().map { auth -> Triple("${auth.label}-happy", auth, null as String?) }
  private val kills =
    Auth.values().flatMap { auth ->
      BOUNDARIES.map { boundary -> Triple("${auth.label}-kill-$boundary", auth, boundary as String?) }
    }

  @Test
  fun theHappyPathJournalsAsBefore() {
    checkAll(happy)
  }

  @Test
  fun eachKillPointJournalsAsBefore() {
    checkAll(kills)
  }

  @Test
  fun theIndexListsEveryScenarioAndTheNormalizer() {
    val actual = index()
    val golden = readGolden("INDEX")
    if (golden == actual) return
    System.getenv("TEST_UNDECLARED_OUTPUTS_DIR")?.let { File(it, "INDEX.txt").writeText(actual) }
    fail("INDEX.txt differs from the scenario set and normalizer; the actual index is in the undeclared outputs")
  }

  /** The golden directory in runfiles: the directory of `INDEX.txt`, whose runfiles path
   * golden_journal_test supplies as GOLDEN_INDEX. */
  private val goldenDir: File by lazy {
    val srcdir = System.getenv("TEST_SRCDIR") ?: error("TEST_SRCDIR not set (not under bazel test)")
    val rloc =
      System.getenv("GOLDEN_INDEX")
        ?: error("GOLDEN_INDEX not set (golden_journal_test supplies it via rlocationpath)")
    val index = File(srcdir, rloc)
    check(index.exists()) { "INDEX.txt not found in runfiles at $index" }
    index.parentFile
  }

  /** The golden named [name], or null if there is none. */
  private fun readGolden(name: String): String? =
    File(goldenDir, "$name.txt").takeIf { it.exists() }?.readText()

  private fun index(): String =
    (VOLATILE.map { (pattern, label) -> "volatile $label ${pattern.pattern}" } +
        "volatile nonce ${NONCE_VALUE.pattern}" +
        (happy + kills).map { "scenario ${it.first}" })
      .joinToString("\n", postfix = "\n")

  /** Checks every scenario before failing, so one run writes every journal that differs. */
  private fun checkAll(scenarios: List<Triple<String, Auth, String?>>) {
    val failures = mutableListOf<String>()
    for ((name, auth, killAt) in scenarios) {
      try {
        check(name, auth, killAt)
      } catch (e: AssertionError) {
        failures += e.message ?: name
      }
    }
    if (failures.isNotEmpty()) fail(failures.joinToString("\n"))
  }

  private fun check(name: String, auth: Auth, killAt: String?) {
    val actual = normalize(walk(auth, killAt), killAt)
    val golden = readGolden(name)
    if (golden == actual) return
    val out = System.getenv("TEST_UNDECLARED_OUTPUTS_DIR")
    if (out != null) File(out, "$name.txt").writeText(actual)
    fail(
      if (golden == null) "$name: no golden file; the actual journal is in the undeclared outputs"
      else "$name: journal differs from its golden; the actual journal is in the undeclared outputs"
    )
  }

  /** Runs the walk: drive, release the plan gate, drive, release the commit gate, drive. With
   * [killAt], the first time the daemon reaches that boundary it dies, and a fresh daemon carries
   * the walk on to done. Returns the journal, and whether the kill fired. */
  private fun walk(auth: Auth, killAt: String?): Run {
    val dir = tmp.newFolder()
    File(dir, "ticket.txt").writeText("t1\n")
    val store = SqliteStore(dir.absolutePath, componentId = "lead")
    var armed = killAt
    val faults = FaultInjector { boundary ->
      if (boundary == armed) {
        armed = null
        throw Killed(boundary)
      }
    }
    var daemon = daemon(dir, store, auth, faults)
    repeat(MAX_DRIVES) {
      val folded =
        try {
          daemon.driveUntilQuiescent()
        } catch (_: Killed) {
          daemon = daemon(dir, store, auth, faults)
          return@repeat
        }
      if ("t1" in folded.lead.doneTickets) {
        val entries = store.readAll()
        store.close()
        return Run(entries, dir, killed = killAt != null && armed == null)
      }
      val pending = folded.host.pendingGates.firstOrNull() ?: return@repeat
      release(store, auth, folded.host, pending)
    }
    store.close()
    fail("$auth walk${killAt?.let { " killed at $it" } ?: ""} did not reach done in $MAX_DRIVES drives")
    error("unreachable")
  }

  private fun release(store: SqliteStore, auth: Auth, host: HostState, gate: OpenGate) {
    when (auth) {
      Auth.DENY_ALL -> AuthStub.appendRelease(store, gate.gateId, gate.payloadDigest)
      Auth.CEREMONY -> store.approveAndRelease(host.openNonceFor(gate) ?: error("no open nonce for ${gate.gateId}"))
    }
  }

  private fun daemon(dir: File, store: SqliteStore, auth: Auth, faults: FaultInjector): AgentHost<LeadState> =
    ticketLead(
      store = store,
      cognition = ScriptedCognition(),
      podRunner = FakePodRunner(),
      podSpec = PodSpec.fixture(),
      ticketSource = FileTicketSource(File(dir, "ticket.txt")),
      workdir = dir,
      effects = EffectReceiver(dir.absolutePath),
      leadAuth = if (auth == Auth.CEREMONY) ceremonyAuth() else LeadAuth.DENY_ALL,
      // A ceremony daemon refuses NOOP; this one fires nothing either, so no announce is retried.
      timers = if (auth == Auth.CEREMONY) TimerService { _, _ -> } else TimerService.NOOP,
      faults = faults,
    )

  private class Run(val entries: List<JournalEntry>, val dir: File, val killed: Boolean)

  /** For a kill scenario, a first line saying whether the kill fired. Then one line per entry: seq,
   * kind, origin, idempotency key, payload. Values that differ between runs are renamed by order of
   * first appearance. */
  private fun normalize(run: Run, killAt: String?): String {
    val entries = run.entries
    val dir = run.dir
    // The nonces the mint drew, by value, so each is renamed wherever it appears: the nonce entry,
    // the approval and its evidence, the release, the announce marker.
    val nonces =
      entries
        .filter { it.kind == LeadKinds.NONCE_ISSUED }
        .mapNotNull { NONCE_VALUE.find(it.payloadJson)?.groupValues?.get(1) }
        .distinct()
    val counts = mutableMapOf<String, Int>()
    val renames = mutableMapOf<String, String>()
    fun label(value: String, kind: String): String =
      renames.getOrPut(value) { "$kind#${counts.merge(kind, 1, Int::plus)}" }
    fun rename(text: String): String {
      var t = text.replace(dir.canonicalPath, "<DIR>").replace(dir.absolutePath, "<DIR>")
      for (n in nonces) if (n in t) t = t.replace(n, label(n, "nonce"))
      for ((pattern, kind) in VOLATILE) t = pattern.replace(t) { m -> label(m.value, kind) }
      return t
    }
    val header =
      when {
        killAt == null -> ""
        run.killed -> "# kill at $killAt: fired\n"
        else -> "# kill at $killAt: not reached\n"
      }
    return header +
      entries.joinToString("\n", postfix = "\n") { e ->
        "${e.seq} ${e.kind} ${e.origin} key=${e.idempotencyKey?.let(::rename)} ${rename(e.payloadJson)}"
      }
  }

  private companion object {
    const val MAX_DRIVES = 12

    /** Every boundary the walk can reach. A boundary the walk does not reach under an auth leaves
     * that scenario's journal equal to the happy path's, which the golden still pins. */
    val BOUNDARIES =
      listOf(
        "mid-adopt",
        "after-redrive",
        "after-claim",
        "after-plan-requested",
        "after-spawn-intended",
        "between-spawn-and-journal",
        "after-pod-spawned",
        "after-pod-result",
        "after-plan-recorded",
        "after-gate-opened-plan-approval",
        "after-gate-announced",
        "after-commit-proposed",
        "after-gate-opened-commit-approval",
        "after-commit-intent",
        "after-commit-effect",
        "after-ticket-done",
      )

    /** What differs between runs besides nonces: the fake runner's random pod and session ids.
     * Session first, so its UUID is not taken for a pod id. */
    val VOLATILE =
      listOf(
        Regex("fake-session-[0-9a-f-]{36}") to "session",
        Regex("pod-[0-9a-f]{8}") to "pod",
      )

    val NONCE_VALUE = Regex("\"nonce\":\"([^\"]+)\"")
  }
}
